"""Generate crates/voxel-data/src/item/tooltip.rs from a block-family capture.

    python3 tools/generate/tooltip_registries.py .data/captures/behavior/<id>/outputs.jsonl

What an item's tooltip reads its texts from, by registry id, from the
reference: enchantments, painting variants, instruments, jukebox songs,
banner patterns, trim materials and patterns and attributes. The capture is
local; the generated table is committed, and the parity run compares it
with the reference on every pass.
"""
import json
import sys


def literal(text):
    return json.dumps(text)


def rust(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main(path):
    data = None
    for line in open(path, encoding="utf-8"):
        case = json.loads(line)
        if case["case_id"] == "block/tooltip-registries":
            data = case["result"]["rows"][0]
    if data is None:
        raise SystemExit("no block/tooltip-registries case in the capture")

    def component(value):
        return rust(json.dumps(value, separators=(",", ":"))) if value is not None else '""'

    out = [
        "//! What an item's tooltip reads its texts from, by registry id, from the",
        "//! reference. A component is its JSON.",
        "//!",
        "//! This file is generated by `tools/generate/tooltip_registries.py`.",
        "",
        "pub struct Enchantment {",
        "    pub name: &'static str,",
        "    pub description: &'static str,",
        "    /// In the `curse` tag.",
        "    pub curse: bool,",
        "    pub max_level: i32,",
        "    /// Its place in the `tooltip_order` tag, or -1.",
        "    pub tooltip_order: i32,",
        "}",
        "",
        "pub struct PaintingVariant {",
        "    pub name: &'static str,",
        "    pub width: i32,",
        "    pub height: i32,",
        "    /// Empty when the variant has none.",
        "    pub title: &'static str,",
        "    pub author: &'static str,",
        "}",
        "",
        "/// An entry that is a name and a description: instruments, jukebox",
        "/// songs, trim materials and trim patterns.",
        "pub struct Described {",
        "    pub name: &'static str,",
        "    pub description: &'static str,",
        "}",
        "",
        "pub struct BannerPattern {",
        "    pub name: &'static str,",
        "    pub translation_key: &'static str,",
        "}",
        "",
        "pub struct Attribute {",
        "    pub name: &'static str,",
        "    pub description_id: &'static str,",
        "    /// The formatting a rise and a fall of it show in.",
        "    pub style_up: &'static str,",
        "    pub style_down: &'static str,",
        "}",
        "",
        "#[rustfmt::skip]",
        f"pub static ENCHANTMENTS: [Enchantment; {len(data['enchantments'])}] = [",
    ]
    for e in data["enchantments"]:
        out.append(
            f'    Enchantment {{ name: {rust(e["name"])}, description: {component(e["description"])}, '
            f'curse: {str(e["curse"]).lower()}, max_level: {e["max_level"]}, tooltip_order: {e["tooltip_order"]} }},'
        )
    out += ["];", "", "#[rustfmt::skip]", f"pub static PAINTING_VARIANTS: [PaintingVariant; {len(data['painting_variants'])}] = ["]
    for e in data["painting_variants"]:
        out.append(
            f'    PaintingVariant {{ name: {rust(e["name"])}, width: {e["width"]}, height: {e["height"]}, '
            f'title: {component(e.get("title"))}, author: {component(e.get("author"))} }},'
        )
    out.append("];")
    for key, name in (
        ("instruments", "INSTRUMENTS"),
        ("jukebox_songs", "JUKEBOX_SONGS"),
        ("trim_materials", "TRIM_MATERIALS"),
        ("trim_patterns", "TRIM_PATTERNS"),
    ):
        out += ["", "#[rustfmt::skip]", f"pub static {name}: [Described; {len(data[key])}] = ["]
        for e in data[key]:
            out.append(f'    Described {{ name: {rust(e["name"])}, description: {component(e["description"])} }},')
        out.append("];")
    out += ["", "#[rustfmt::skip]", f"pub static BANNER_PATTERNS: [BannerPattern; {len(data['banner_patterns'])}] = ["]
    for e in data["banner_patterns"]:
        out.append(f'    BannerPattern {{ name: {rust(e["name"])}, translation_key: {rust(e["translation_key"])} }},')
    out += ["];", "", "#[rustfmt::skip]", f"pub static ATTRIBUTES: [Attribute; {len(data['attributes'])}] = ["]
    for e in data["attributes"]:
        out.append(
            f'    Attribute {{ name: {rust(e["name"])}, description_id: {rust(e["description_id"])}, '
            f'style_up: {rust(e["style_up"])}, style_down: {rust(e["style_down"])} }},'
        )
    out += ["];", ""]
    open("crates/voxel-data/src/item/tooltip.rs", "w", encoding="utf-8").write("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
