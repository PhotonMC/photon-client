"""Generate crates/voxel-data/src/block/outline.rs from a block-family capture.

    python3 tools/generate/block_outline.py .data/captures/behavior/<id>/outputs.jsonl

The capture is local; the generated table is committed, and the parity run
compares it with the reference on every pass.
"""
import json
import sys


def main(path):
    data = None
    for line in open(path, encoding="utf-8"):
        record = json.loads(line)
        if record["case_id"] == "block/outline-shapes":
            data = record["result"]["rows"][0]
    if data is None:
        raise SystemExit("no block/outline-shapes record in that capture")

    shapes, blocks = data["shapes"], data["blocks"]
    lines = [
        "//! Every block state's outline shape, taken from the reference.",
        "//!",
        "//! The outline is the shape picking aims at: what a click on a block hits.",
        "//! It is often not the collision shape; plants have an outline and no",
        "//! collision. Shapes are deduplicated by their boxes, and a block whose",
        "//! states all share one shape carries a single entry.",
        "//!",
        "//! A block whose outline moves with its random offset is listed with the",
        "//! shape it is built from, before the offset; the reference moves it by",
        "//! the offset at the block's position. The few dynamic shapes read the",
        "//! entity or the block entity, and are flagged.",
        "//!",
        "//! This file is generated by `tools/generate/block_outline.py`.",
        "",
        "/// What one block's outline shapes are and how far to trust them.",
        "pub struct BlockOutline {",
        "    /// Indices into [`SHAPES`]: one for every state, or one per state.",
        "    pub shapes: &'static [u16],",
        "    /// The shape moves with the block's random offset.",
        "    pub offset: bool,",
        "    /// The reference recomputes the shape from context rather than caching it.",
        "    pub dynamic: bool,",
        "}",
        "",
        "/// Every distinct shape, as its boxes: raw `f64` bits of min x, y, z then",
        f"/// max x, y, z.\npub static SHAPES: [&[[u64; 6]]; {len(shapes)}] = [",
    ]
    for shape in shapes:
        boxes = ", ".join(
            "[" + ", ".join(f"0x{bits}" for bits in box) + "]" for box in shape
        )
        lines.append(f"    &[{boxes}],")
    lines.append("];")
    lines.append("")
    lines.append(
        f"/// Every block's outline, in registry order.\n"
        f"pub static BLOCKS: [BlockOutline; {len(blocks)}] = ["
    )
    for block in blocks:
        if not block["offset_explained"]:
            raise SystemExit(f"{block['name']}: outline not explained by its offset")
        indices = ", ".join(str(index) for index in block["shapes"])
        lines.append(
            f"    BlockOutline {{ shapes: &[{indices}], "
            f"offset: {str(block['position_dependent']).lower()}, "
            f"dynamic: {str(block['dynamic']).lower()} }},"
        )
    lines.append("];")
    with open("crates/voxel-data/src/block/outline.rs", "w", encoding="utf-8") as out:
        out.write("\n".join(lines) + "\n")
    print(f"shapes={len(shapes)} blocks={len(blocks)}")


if __name__ == "__main__":
    main(sys.argv[1])
