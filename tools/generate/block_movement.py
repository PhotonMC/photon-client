"""Generate crates/voxel-data/src/block/movement.rs from a block-family capture.

    python3 tools/generate/block_movement.py .data/captures/behavior/<id>/outputs.jsonl

The capture is local; the generated table is committed, and the parity run
compares it with the reference on every pass.
"""
from common import f32, intern, load_case, run, write

FLAGS = [
    ("climbable", "CLIMBABLE"),
    ("fence", "FENCE"),
    ("wall", "WALL"),
    ("can_glide_through", "CAN_GLIDE_THROUGH"),
    ("suppresses_bounce", "SUPPRESSES_BOUNCE"),
    ("fence_gate", "FENCE_GATE"),
    ("trapdoor", "TRAPDOOR"),
    ("ladder", "LADDER"),
]
FLUID_KINDS = {
    "minecraft:empty": "Empty",
    "minecraft:water": "Water",
    "minecraft:flowing_water": "FlowingWater",
    "minecraft:lava": "Lava",
    "minecraft:flowing_lava": "FlowingLava",
}


def generate(capture):
    data = load_case(capture, "block/movement-properties")
    traits, indices = intern(block["fluids"] for block in data["blocks"])
    rows = []
    for block, ids in zip(data["blocks"], indices):
        flags = " | ".join(f"flag::{name}" for field, name in FLAGS if block[field]) or "0"
        rows.append((block, ids, flags))

    out = [
        "//! What each block contributes to movement beyond its shape, from the reference.",
        "//!",
        "//! The three block factors, the bounce, the tags and block classes the movement",
        "//! code tests, and for every state the fluid it holds and whether it suffocates.",
        "//! The tags are the vanilla data pack's, which is what a vanilla server sends in",
        "//! its tag packet.",
        "//!",
        "//! This file is generated by `tools/generate/block_movement.py`.",
        "",
        "/// Tag and class flags.",
        "pub mod flag {",
    ]
    for bit, (_, name) in enumerate(FLAGS):
        out.append(f"    pub const {name}: u16 = 1 << {bit};")
    out += [
        "}",
        "",
        "/// Which fluid a state holds.",
        "#[derive(Clone, Copy, PartialEq, Eq, Debug)]",
        "pub enum FluidKind {",
        "    Empty,",
        "    Water,",
        "    FlowingWater,",
        "    Lava,",
        "    FlowingLava,",
        "}",
        "",
        "/// The fluid a state holds and whether it suffocates.",
        "pub struct StateTraits {",
        "    pub fluid: FluidKind,",
        "    /// The fluid's level, eight for a source.",
        "    pub amount: u8,",
        "    /// A flowing fluid falling from above.",
        "    pub falling: bool,",
        "    /// `FluidState.getOwnHeight`.",
        "    pub own_height: f32,",
        "    pub source: bool,",
        "    pub suffocating: bool,",
        "}",
        "",
        "/// One block's movement properties.",
        "pub struct BlockMovement {",
        "    pub friction: f32,",
        "    pub speed_factor: f32,",
        "    pub jump_factor: f32,",
        "    pub bounce_restitution: f32,",
        "    pub flags: u16,",
        "    /// Indices into [`STATE_TRAITS`]: one for every state, or one per state.",
        "    pub states: &'static [u16],",
        "}",
        "",
        f"/// Every distinct state trait set.\n#[rustfmt::skip]\npub static STATE_TRAITS: [StateTraits; {len(traits)}] = [",
    ]
    for key in traits:
        fluid, amount, falling, height, source, suffocating = key.split("|")
        out.append(
            f"    StateTraits {{ fluid: FluidKind::{FLUID_KINDS[fluid]}, amount: {amount}, "
            f"falling: {falling}, own_height: {f32(height)}, source: {source}, "
            f"suffocating: {suffocating} }},"
        )
    out += ["];", "", f"/// Every block, in registry order.\n#[rustfmt::skip]\npub static BLOCKS: [BlockMovement; {len(rows)}] = ["]
    for block, ids, flags in rows:
        out.append(
            f"    BlockMovement {{ friction: {f32(block['friction'])}, speed_factor: {f32(block['speed_factor'])}, "
            f"jump_factor: {f32(block['jump_factor'])}, bounce_restitution: {f32(block['bounce_restitution'])}, "
            f"flags: {flags}, states: &[{', '.join(map(str, ids))}] }},"
        )
    out.append("];")
    write("block/movement.rs", out)
    print(f"traits={len(traits)} blocks={len(rows)}")


if __name__ == "__main__":
    run(generate)
