"""Generate src/world/block_destroy_table.rs from a block-family capture.

    python3 tools/generate/block_destroy.py .data/captures/behavior/<id>/outputs.jsonl

What breaking reads of each state, from the reference: the destroy time, whether
drops need the right tool, whether it is air, and the state the client predicts
in its place. Game master blocks are listed by registry index. The capture is
local; the generated table is committed, and the parity run compares it with
the reference on every pass.
"""
import json
import sys


def main(path):
    data = None
    for line in open(path, encoding="utf-8"):
        case = json.loads(line)
        if case["case_id"] == "block/destroy-properties":
            data = case["result"]["rows"][0]
    if data is None:
        raise SystemExit("no block/destroy-properties case in the capture")
    traits = []
    index = {}
    rows = []
    game_master = []
    for number, block in enumerate(data["blocks"]):
        if block["game_master"]:
            game_master.append(number)
        ids = []
        for key in block["states"]:
            if key not in index:
                index[key] = len(traits)
                traits.append(key)
            ids.append(index[key])
        rows.append(ids)
    out = [
        "//! What breaking a block reads of each state, from the reference.",
        "//!",
        "//! This file is generated by `tools/generate/block_destroy.py`.",
        "",
        "/// One set of destroy traits.",
        "pub struct DestroyTraits {",
        "    /// The destroy time as raw `f32` bits; -1 cannot be broken.",
        "    pub destroy_time: u32,",
        "    pub requires_correct_tool: bool,",
        "    pub air: bool,",
        "    /// The state left in its place: the block of the fluid it holds.",
        "    pub fluid_block: u32,",
        "}",
        "",
        "#[rustfmt::skip]",
        f"pub static TRAITS: [DestroyTraits; {len(traits)}] = [",
    ]
    for key in traits:
        speed, requires, air, fluid = key.split("|")
        out.append(
            f"    DestroyTraits {{ destroy_time: 0x{speed}, requires_correct_tool: {requires}, "
            f"air: {air}, fluid_block: {fluid} }},"
        )
    out += ["];", "", "/// Each block's traits: one for every state, or one per state.",
            "#[rustfmt::skip]", f"pub static BLOCKS: [&[u16]; {len(rows)}] = ["]
    for ids in rows:
        out.append("    &[" + ", ".join(str(i) for i in ids) + "],")
    out += ["];", "", "/// The registry indices of game master blocks.",
            f"pub static GAME_MASTER: [u16; {len(game_master)}] = ["
            + ", ".join(str(i) for i in game_master) + "];", ""]
    with open("src/world/block_destroy_table.rs", "w", encoding="utf-8") as handle:
        handle.write("\n".join(out))
    print(f"traits={len(traits)} blocks={len(rows)} game_master={len(game_master)}")


if __name__ == "__main__":
    main(sys.argv[1])
