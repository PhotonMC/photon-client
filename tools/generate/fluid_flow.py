"""Generate src/world/fluid_flow_table.rs from a block-family capture.

    python3 tools/generate/fluid_flow.py .data/captures/behavior/<id>/outputs.jsonl

What a fluid's flow reads of each state, from the reference: the fully sturdy
faces (none for ice blocks) and whether the state blocks motion, as runs over
state ids. The parity run compares the table with the reference on every pass.
"""
import json
import sys


def main(path):
    data = None
    for line in open(path, encoding="utf-8"):
        case = json.loads(line)
        if case["case_id"] == "block/fluid-flow-properties":
            data = case["result"]["rows"][0]
    if data is None:
        raise SystemExit("no block/fluid-flow-properties case in the capture")
    runs = [tuple(int(part) for part in run.split(":")) for run in data["runs"]]
    out = [
        "//! What a fluid's flow reads of each state, from the reference: bits 0 to 5",
        "//! are the fully sturdy faces in direction order (never for an ice block),",
        "//! bit 6 whether the state blocks motion. Runs over state ids, each its",
        "//! first state and value.",
        "//!",
        "//! This file is generated by `tools/generate/fluid_flow.py`.",
        "",
        f"pub const STATE_COUNT: usize = {data['state_count']};",
        "",
        "#[rustfmt::skip]",
        f"pub static RUNS: [(u32, u8); {len(runs)}] = [",
    ]
    for start in range(0, len(runs), 8):
        chunk = runs[start:start + 8]
        out.append("    " + " ".join(f"({first}, {value})," for first, value in chunk))
    out += ["];", ""]
    with open("src/world/fluid_flow_table.rs", "w", encoding="utf-8") as handle:
        handle.write("\n".join(out))
    print(f"states={data['state_count']} runs={len(runs)}")


if __name__ == "__main__":
    main(sys.argv[1])
