"""Generate crates/voxel-data/src/block/fluid_overlay.rs from a block-family capture.

    python3 tools/generate/fluid_overlay.py .data/captures/behavior/<id>/outputs.jsonl

The blocks a water side shows its overlay sprite against, from the
reference. The parity run compares the table with the reference on every
pass.
"""

from common import load_case, run, write


def generate(capture):
    data = load_case(capture, "block/fluid-overlay-blocks")
    out = [
        "//! The blocks a fluid side shows its overlay sprite against, from the",
        "//! reference: its half-transparent blocks and its leaves.",
        "//!",
        "//! This file is generated by `tools/generate/fluid_overlay.py`.",
        "",
        "#[rustfmt::skip]",
        f"pub static OVERLAY_BLOCKS: [&str; {len(data['blocks'])}] = [",
    ]
    for block in data["blocks"]:
        out.append(f"    \"{block}\",")
    out += ["];", ""]
    write("block/fluid_overlay.rs", out)
    print(f"blocks={len(data['blocks'])}")


if __name__ == "__main__":
    run(generate)
