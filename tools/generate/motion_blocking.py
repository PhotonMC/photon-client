"""Generate crates/voxel-data/src/block/motion_blocking.rs from a block-family capture.

    python3 tools/generate/motion_blocking.py .data/captures/behavior/<id>/outputs.jsonl

Which states the MOTION_BLOCKING heightmap counts, one bit per state id, from
the reference. The parity run compares the table with the reference on every
pass.
"""

from common import load_case, run, write


def generate(capture):
    data = load_case(capture, "block/motion-blocking")
    out = [
        "//! Which states the MOTION_BLOCKING heightmap counts, from the reference:",
        "//! states that block motion or hold a fluid. One bit per state id, lowest",
        "//! bit first.",
        "//!",
        "//! This file is generated by `tools/generate/motion_blocking.py`.",
        "",
        f"pub const STATE_COUNT: usize = {data['state_count']};",
        "",
        "#[rustfmt::skip]",
        f"pub static WORDS: [u64; {len(data['words'])}] = [",
    ]
    for start in range(0, len(data["words"]), 4):
        chunk = data["words"][start:start + 4]
        out.append("    " + " ".join(f"0x{word}," for word in chunk))
    out += ["];", ""]
    write("block/motion_blocking.rs", out)
    print(f"states={data['state_count']} words={len(data['words'])}")


if __name__ == "__main__":
    run(generate)
