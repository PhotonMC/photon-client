"""Generate crates/voxel-data/src/block/behaviour.rs from a block-family capture.

    python3 tools/generate/block_behaviour.py .data/captures/behavior/<id>/outputs.jsonl

Which class's own rule each block runs for placement, replacement, survival,
use and neighbour shape updates, each state's replaceable flag, whether it is
a stair, and the item it drops as. Items get their class, the classes whose
use rules they run, whether the default `Item.use` does nothing for them, and
the block a block item places. The capture is local; the generated table is
committed, and the parity run compares it with the reference on every pass.
"""

from common import load_case, run, write


def generate(capture):
    data = load_case(capture, "block/behaviours")
    classes = []
    index = {}

    def cls(name):
        if name not in index:
            index[name] = len(classes)
            classes.append(name)
        return index[name]

    block_index = {block["name"]: i for i, block in enumerate(data["blocks"])}
    item_index = {item["name"]: i for i, item in enumerate(data["items"])}
    block_rows = []
    for block in data["blocks"]:
        block_rows.append(
            f'    BlockBehaviour {{ class: {cls(block["class"])}, placement: {cls(block["placement"])}, '
            f'can_be_replaced: {cls(block["can_be_replaced"])}, can_survive: {cls(block["can_survive"])}, '
            f'use_without_item: {cls(block["use_without_item"])}, use_item_on: {cls(block["use_item_on"])}, '
            f'update_shape: {cls(block["update_shape"])}, stairs: {str(block["stairs"]).lower()}, '
            f'item: {item_index[block["item"]]}, replaceable: "{block["replaceable"]}" }},'
        )
    item_rows = []
    for item in data["items"]:
        block = item.get("block")
        placed = "None" if block is None else f"Some({block_index[block]})"
        item_rows.append(
            f'    ItemBehaviour {{ class: {cls(item["class"])}, use_on: {cls(item["use_on"])}, '
            f'use_: {cls(item["use"])}, default_use_pass: {str(item["default_use_pass"]).lower()}, '
            f'block: {placed} }},'
        )
    out = [
        "//! Which class's own rule each block and item runs, from the reference.",
        "//!",
        "//! This file is generated by `tools/generate/block_behaviour.py`.",
        "",
        "pub struct BlockBehaviour {",
        "    /// Indices into [`CLASSES`]: the block's class, then the class whose",
        "    /// own method each rule resolves to.",
        "    pub class: u16,",
        "    pub placement: u16,",
        "    pub can_be_replaced: u16,",
        "    pub can_survive: u16,",
        "    pub use_without_item: u16,",
        "    pub use_item_on: u16,",
        "    pub update_shape: u16,",
        "    /// `instanceof StairBlock`.",
        "    pub stairs: bool,",
        "    /// The registry id of the item it drops as (`asItem`).",
        "    pub item: u16,",
        "    /// `BlockState.canBeReplaced` for each state, as `0`/`1`.",
        "    pub replaceable: &'static str,",
        "}",
        "",
        "pub struct ItemBehaviour {",
        "    pub class: u16,",
        "    pub use_on: u16,",
        "    pub use_: u16,",
        "    /// Whether the default `Item.use` does nothing for the default stack.",
        "    pub default_use_pass: bool,",
        "    /// The block a block item places, by registry index.",
        "    pub block: Option<u16>,",
        "}",
        "",
        "#[rustfmt::skip]",
        f"pub static BLOCKS: [BlockBehaviour; {len(block_rows)}] = [",
        *block_rows,
        "];",
        "",
        "#[rustfmt::skip]",
        f"pub static ITEMS: [ItemBehaviour; {len(item_rows)}] = [",
        *item_rows,
        "];",
        "",
        "#[rustfmt::skip]",
        f"pub static CLASSES: [&str; {len(classes)}] = [",
        *[f'    "{name}",' for name in classes],
        "];",
        "",
    ]
    write("block/behaviour.rs", out)
    print(f"blocks={len(block_rows)} items={len(item_rows)} classes={len(classes)}")


if __name__ == "__main__":
    run(generate)
