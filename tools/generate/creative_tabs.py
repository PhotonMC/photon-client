"""Generate src/creative_tabs_table.rs from a block-family capture.

    python3 tools/generate/creative_tabs.py .data/captures/behavior/<id>/outputs.jsonl

The creative inventory's tabs and what each shows, in the reference's
order. A stack is its item and component patch as the network encodes it,
stored once and referred to by index. The capture is local; the generated
table is committed, and the parity run compares it with the reference on
every pass.
"""
import json
import sys


def read_varint(data, at):
    value = 0
    shift = 0
    while True:
        byte = data[at]
        at += 1
        value |= (byte & 0x7F) << shift
        if not byte & 0x80:
            return value, at
        shift += 7


def main(path):
    data = None
    for line in open(path, encoding="utf-8"):
        case = json.loads(line)
        if case["case_id"] == "block/creative-tabs":
            data = case["result"]["rows"][0]
    if data is None:
        raise SystemExit("no block/creative-tabs case in the capture")

    stacks = []
    index = {}

    def stack(entry):
        if entry["wire"] not in index:
            wire = bytes.fromhex(entry["wire"])
            count, at = read_varint(wire, 0)
            assert count == 1, entry
            item, at = read_varint(wire, at)
            index[entry["wire"]] = len(stacks)
            stacks.append((item, entry["positive"], entry["negative"], wire[at:], entry["item"]))
        return index[entry["wire"]]

    tabs = []
    for tab in data["tabs"]:
        tabs.append((tab, stack(tab["icon"]), [stack(item) for item in tab["items"]]))

    def ids(values):
        return "&[" + ", ".join(str(value) for value in values) + "]"

    out = [
        "//! The creative inventory's tabs and what each shows, in the reference's",
        "//! order, for the default features and a player without operator",
        "//! permissions.",
        "//!",
        "//! This file is generated by `tools/generate/creative_tabs.py`.",
        "",
        "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
        "pub enum TabKind {",
        "    Category,",
        "    Inventory,",
        "    Hotbar,",
        "    Search,",
        "}",
        "",
        "/// An item and its component patch as the network encodes it.",
        "pub struct CreativeStack {",
        "    pub item: i32,",
        "    pub positive: &'static [i32],",
        "    pub negative: &'static [i32],",
        "    /// From the positive component count on.",
        "    pub patch: &'static [u8],",
        "}",
        "",
        "pub struct CreativeTab {",
        "    pub name: &'static str,",
        "    pub kind: TabKind,",
        "    pub top: bool,",
        "    pub column: i32,",
        "    pub aligned_right: bool,",
        "    pub show_title: bool,",
        "    pub can_scroll: bool,",
        "    pub should_display: bool,",
        "    pub background: &'static str,",
        "    pub title: &'static str,",
        "    pub icon: u16,",
        "    pub items: &'static [u16],",
        "}",
        "",
        f"pub const DEFAULT_TAB: &str = \"{data['default_tab']}\";",
        "",
        "#[rustfmt::skip]",
        f"pub static CREATIVE_STACKS: [CreativeStack; {len(stacks)}] = [",
    ]
    for item, positive, negative, patch, name in stacks:
        patch_bytes = ", ".join(f"0x{byte:02x}" for byte in patch)
        out.append(
            f"    CreativeStack {{ item: {item}, positive: {ids(positive)}, negative: {ids(negative)}, "
            f"patch: &[{patch_bytes}] }}, // {name}"
        )
    out.append("];")
    out.append("")
    out.append("#[rustfmt::skip]")
    out.append(f"pub static CREATIVE_TABS: [CreativeTab; {len(tabs)}] = [")
    for tab, icon, items in tabs:
        kind = tab["type"].capitalize()
        out.append("    CreativeTab {")
        out.append(f'        name: "{tab["name"]}", kind: TabKind::{kind}, top: {str(tab["row"] == "TOP").lower()}, column: {tab["column"]},')
        out.append(
            f'        aligned_right: {str(tab["aligned_right"]).lower()}, show_title: {str(tab["show_title"]).lower()}, '
            f'can_scroll: {str(tab["can_scroll"]).lower()}, should_display: {str(tab["should_display"]).lower()},'
        )
        out.append(f'        background: "{tab["background"]}", title: "{tab["title"]}", icon: {icon},')
        chunks = [items[i : i + 24] for i in range(0, len(items), 24)]
        out.append("        items: &[")
        for chunk in chunks:
            out.append("            " + ", ".join(str(value) for value in chunk) + ",")
        out.append("        ],")
        out.append("    },")
    out.append("];")
    out.append("")
    open("src/creative_tabs_table.rs", "w", encoding="utf-8").write("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
