"""Generate src/world/block_light_table.rs from a block-family capture.

    python3 tools/generate/block_light.py .data/captures/behavior/<id>/outputs.jsonl

What the block renderer's lighting reads of each state, from the reference:
light emission, full-bright rendering, the ambient occlusion shade, whether it
blocks the view, light dampening, solid rendering and a full collision shape.
The capture is local; the generated table is committed, and the parity run
compares it with the reference on every pass.
"""
import json
import sys


def main(path):
    data = None
    for line in open(path, encoding="utf-8"):
        case = json.loads(line)
        if case["case_id"] == "block/light-properties":
            data = case["result"]["rows"][0]
    if data is None:
        raise SystemExit("no block/light-properties case in the capture")
    traits = []
    index = {}
    rows = []
    for block in data["blocks"]:
        ids = []
        for key in block["states"]:
            if key not in index:
                index[key] = len(traits)
                traits.append(key)
            ids.append(index[key])
        rows.append(ids)
    out = [
        "//! What the block renderer's lighting reads of each state, from the reference.",
        "//!",
        "//! This file is generated by `tools/generate/block_light.py`.",
        "",
        "/// One set of lighting traits.",
        "pub struct LightTraits {",
        "    pub emission: u8,",
        "    /// Drawn at full brightness whatever the light around it.",
        "    pub emissive: bool,",
        "    /// The ambient occlusion shade it casts, as raw `f32` bits.",
        "    pub shade: u32,",
        "    pub view_blocking: bool,",
        "    pub dampening: u8,",
        "    pub solid_render: bool,",
        "    pub collision_full_block: bool,",
        "    /// Light is stopped by the shape rather than the whole block.",
        "    pub use_shape_for_light_occlusion: bool,",
        "    pub can_occlude: bool,",
        "}",
        "",
        "#[rustfmt::skip]",
        f"pub static TRAITS: [LightTraits; {len(traits)}] = [",
    ]
    for key in traits:
        emission, emissive, shade, view, damp, solid, full, use_shape, occlude = key.split("|")
        out.append(
            f"    LightTraits {{ emission: {emission}, emissive: {emissive}, shade: 0x{shade}, "
            f"view_blocking: {view}, dampening: {damp}, solid_render: {solid}, "
            f"collision_full_block: {full}, use_shape_for_light_occlusion: {use_shape}, "
            f"can_occlude: {occlude} }},"
        )
    out += ["];", "", "/// Each block's traits: one for every state, or one per state.",
            "#[rustfmt::skip]", f"pub static BLOCKS: [&[u16]; {len(rows)}] = ["]
    for ids in rows:
        out.append("    &[" + ", ".join(str(i) for i in ids) + "],")
    out += ["];", ""]
    with open("src/world/block_light_table.rs", "w", encoding="utf-8") as handle:
        handle.write("\n".join(out))
    print(f"traits={len(traits)} blocks={len(rows)}")


if __name__ == "__main__":
    main(sys.argv[1])
