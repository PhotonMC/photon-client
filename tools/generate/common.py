"""What every table generator shares.

A generator reads one case from a behaviour capture (the reference's own
answer), and writes a Rust file under `crates/photon-data/src`. The parity run
then compares the written table with the reference on every pass, so the
table is never trusted blindly.

Floats are written as the shortest decimal that reads back as exactly the
reference's bits, so the tables stay readable and nothing is lost.
"""
import gzip
import json
import struct
import sys
from fractions import Fraction

DATA = "crates/photon-data/src"


def load_rows(path, case_id):
    """Every row of a case's result in a capture.

    A capture is either a plain `outputs.jsonl` or a parity store
    (`.data/parity/<version>/<family>.jsonl.gz`, whose lines wrap the case in `record`).
    """
    opener = gzip.open if path.endswith(".gz") else open
    for line in opener(path, "rt", encoding="utf-8"):
        case = json.loads(line)
        case = case.get("record", case)
        if case["case_id"] == case_id:
            return case["result"]["rows"]
    raise SystemExit(f"no {case_id} case in {path}")


def load_case(path, case_id):
    """The first row of a case's result in a capture."""
    return load_rows(path, case_id)[0]


def write(relative, lines):
    """Write a generated file under the data crate's `generated/` directory."""
    with open(f"{DATA}/generated/{relative}", "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines).rstrip("\n") + "\n")


def header(summary, generator, notes=()):
    """The doc comment a generated file starts with."""
    lines = [f"//! {summary}"]
    for note in notes:
        lines.append("//!" if not note else f"//! {note}")
    lines += ["//!", f"//! This file is generated by `tools/generate/{generator}`.", ""]
    return lines


def rust_bool(value):
    return "true" if value else "false"


def rust_str(text):
    return json.dumps(text, ensure_ascii=False)


def _nearest(value, below, above, candidate):
    """Whether `candidate` is strictly nearer `value` than its neighbours."""
    exact = Fraction(candidate)
    return abs(exact - value) < abs(exact - below) and abs(exact - value) < abs(exact - above)


def _literal(text):
    """A decimal as a Rust float literal (always with a point or exponent)."""
    if "e" in text or "." in text or "inf" in text or "nan" in text:
        return text
    return text + ".0"


def _shortest(bits, width):
    fmt, size = (">f", 4) if width == 32 else (">d", 8)
    int_fmt = ">I" if width == 32 else ">Q"

    def value_of(raw):
        return struct.unpack(fmt, struct.pack(int_fmt, raw))[0]

    value = value_of(bits)
    if value != value or value in (float("inf"), float("-inf")):
        raise SystemExit(f"non-finite float bits {bits:x} in a table")
    if value == 0:
        return "-0.0" if bits >> (width - 1) else "0.0"
    exact = Fraction(value)
    below = Fraction(value_of(bits - 1)) if bits & ((1 << (width - 1)) - 1) else -exact
    next_up = value_of(bits + 1)
    # Past the largest finite value the next step is infinity: mirror the gap.
    above = exact + (exact - below) if next_up in (float("inf"), float("-inf")) else Fraction(next_up)
    for precision in range(1, 18):
        candidate = f"{value:.{precision}g}"
        if _nearest(exact, below, above, candidate):
            # `1e+02` reads better as `100.0` when that is the same decimal.
            plain = repr(float(candidate))
            if "e" not in plain and Fraction(plain) == Fraction(candidate):
                return _literal(plain)
            return _literal(candidate)
    return _literal(repr(value))


def f32(bits_hex):
    """An `f32` literal for the reference's raw bits (hex text)."""
    return _shortest(int(bits_hex, 16), 32)


def f64(bits_hex):
    """An `f64` literal for the reference's raw bits (hex text)."""
    return _shortest(int(bits_hex, 16), 64)


def byte_slice(data):
    """A `&[u8]` literal."""
    return "&[" + ", ".join(f"0x{byte:02x}" for byte in data) + "]"


def run(generate):
    """Run a generator on the capture named on the command line."""
    if len(sys.argv) != 2:
        raise SystemExit(f"usage: python3 {sys.argv[0]} .data/captures/behavior/<id>/outputs.jsonl")
    generate(sys.argv[1])


def intern(groups):
    """Each group's keys as indices into one list of distinct keys:
    `(distinct keys, index lists)`, in first-seen order."""
    distinct, index, rows = [], {}, []
    for keys in groups:
        ids = []
        for key in keys:
            if key not in index:
                index[key] = len(distinct)
                distinct.append(key)
            ids.append(index[key])
        rows.append(ids)
    return distinct, rows


def index_list(ids):
    return "&[" + ", ".join(str(i) for i in ids) + "]"


