"""Generate crates/voxel-data/src/item/registry.rs from a block-family capture.

    python3 tools/generate/item_tools.py .data/captures/behavior/<id>/outputs.jsonl

Every item in registry order, with the tool component it carries by default,
from the reference. Identical tools are written once. The capture is local; the
generated table is committed, and the parity run compares it with the reference
on every pass.
"""
import json

from common import f32, load_case, run, write


def generate(capture):
    data = load_case(capture, "block/item-tools")
    tools = []
    index = {}
    items = []
    for item in data["items"]:
        tool = item.get("tool")
        number = None
        if tool is not None:
            key = json.dumps(tool, sort_keys=True)
            if key not in index:
                index[key] = len(tools)
                tools.append(tool)
            number = index[key]
        items.append((item["name"], number))

    def rule(entry):
        blocks = entry["blocks"]
        if isinstance(blocks, str):
            written = f'RuleBlocks::Tag("{blocks[1:]}")'
        else:
            written = "RuleBlocks::Blocks(&[" + ", ".join(f'"{b}"' for b in blocks) + "])"
        speed = f'Some({f32(entry["speed"])})' if "speed" in entry else "None"
        correct = entry.get("correct_for_drops")
        correct = "None" if correct is None else f"Some({str(correct).lower()})"
        return f"ToolRule {{ blocks: {written}, speed: {speed}, correct_for_drops: {correct} }}"

    out = [
        "//! Every item in registry order and the tool component it carries by",
        "//! default, from the reference.",
        "//!",
        "//! This file is generated by `tools/generate/item_tools.py`.",
        "",
        "/// The blocks a tool rule covers.",
        "pub enum RuleBlocks {",
        "    /// A block tag, without the leading `#`.",
        "    Tag(&'static str),",
        "    Blocks(&'static [&'static str]),",
        "}",
        "",
        "pub struct ToolRule {",
        "    pub blocks: RuleBlocks,",
        "    pub speed: Option<f32>,",
        "    pub correct_for_drops: Option<bool>,",
        "}",
        "",
        "/// The `minecraft:tool` component.",
        "pub struct Tool {",
        "    pub rules: &'static [ToolRule],",
        "    pub default_mining_speed: f32,",
        "    pub damage_per_block: i32,",
        "    pub can_destroy_blocks_in_creative: bool,",
        "}",
        "",
        "pub struct ItemDefinition {",
        "    pub name: &'static str,",
        "    pub tool: Option<&'static Tool>,",
        "}",
        "",
        "#[rustfmt::skip]",
        f"pub static TOOLS: [Tool; {len(tools)}] = [",
    ]
    for tool in tools:
        out.append("    Tool {")
        out.append("        rules: &[")
        for entry in tool["rules"]:
            out.append(f"            {rule(entry)},")
        out.append("        ],")
        out.append(f'        default_mining_speed: {f32(tool["default_mining_speed"])},')
        out.append(f'        damage_per_block: {tool["damage_per_block"]},')
        out.append(
            f'        can_destroy_blocks_in_creative: {str(tool["can_destroy_blocks_in_creative"]).lower()},')
        out.append("    },")
    out += ["];", "", "#[rustfmt::skip]", f"pub static ITEMS: [ItemDefinition; {len(items)}] = ["]
    for name, number in items:
        tool = "None" if number is None else f"Some(&TOOLS[{number}])"
        out.append(f'    ItemDefinition {{ name: "{name}", tool: {tool} }},')
    out += ["];", ""]
    write("item/registry.rs", out)
    print(f"items={len(items)} tools={len(tools)}")


if __name__ == "__main__":
    run(generate)
