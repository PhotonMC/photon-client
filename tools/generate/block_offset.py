"""Generate crates/voxel-data/src/block/offset.rs from a block-family capture.

    python3 tools/generate/block_offset.py .data/captures/behavior/<id>/outputs.jsonl

The blocks the renderer nudges off the grid, whether the nudge is vertical
too, and the block's own limits, from the reference. The parity run compares
the table with the reference on every pass.
"""
import json
import sys


def main(path):
    data = None
    for line in open(path, encoding="utf-8"):
        case = json.loads(line)
        if case["case_id"] == "block/offset-properties":
            data = case["result"]["rows"][0]
    if data is None:
        raise SystemExit("no block/offset-properties case in the capture")
    out = [
        "//! The blocks the renderer nudges off the grid, from the reference.",
        "//!",
        "//! Each entry is the block, whether it also moves vertically, and its",
        "//! largest horizontal and vertical nudge as raw `f32` bits.",
        "//!",
        "//! This file is generated by `tools/generate/block_offset.py`.",
        "",
        "#[rustfmt::skip]",
        f"pub static OFFSETS: [(&str, bool, u32, u32); {len(data['blocks'])}] = [",
    ]
    for block in data["blocks"]:
        out.append(
            f"    (\"{block['name']}\", {str(block['kind'] == 'xyz').lower()}, "
            f"0x{block['max_horizontal']}, 0x{block['max_vertical']}),"
        )
    out += ["];", ""]
    with open("crates/voxel-data/src/block/offset.rs", "w", encoding="utf-8") as handle:
        handle.write("\n".join(out))
    print(f"blocks={len(data['blocks'])}")


if __name__ == "__main__":
    main(sys.argv[1])
