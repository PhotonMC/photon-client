"""Generate crates/voxel-data/src/block/face_occlusion.rs from a block-family capture.

    python3 tools/generate/face_occlusion.py .data/captures/behavior/<id>/outputs.jsonl

Everything the reference's face culling reads, as the reference computes it:
each state's six face occlusion shapes, whether one shape sticks out past
another, and which neighbouring blocks hide their shared face. The capture is
local; the generated table is committed, and the parity run compares it with
the reference on every pass.
"""
import json
import sys

DIRECTIONS = ["down", "up", "north", "south", "west", "east"]


def main(path):
    data = None
    for line in open(path, encoding="utf-8"):
        case = json.loads(line)
        if case["case_id"] == "block/face-occlusion":
            data = case["result"]["rows"][0]
    if data is None:
        raise SystemExit("no block/face-occlusion case in the capture")
    index = {block["name"]: i for i, block in enumerate(data["blocks"])}
    out = [
        "//! Every block state's face occlusion shapes, from the reference.",
        "//!",
        "//! A face's occlusion shape is nothing (kind 0), the whole block (kind 1)",
        "//! or one of the partial shapes numbered after them. `TUPLES` holds the six",
        "//! kinds a state uses, in the reference's direction order (down, up, north,",
        "//! south, west, east); `BLOCK_TUPLES` names each state's tuple, one entry",
        "//! when every state of the block shares it. `JOINS` row `a` column `b` says",
        "//! whether shape `a` has any part shape `b` does not cover. `SKIPS` are the",
        "//! block pairs whose shared face is hidden regardless of shapes.",
        "//!",
        "//! This file is generated by `tools/generate/face_occlusion.py`.",
        "",
        "/// One neighbouring pair that hides its shared face.",
        "pub struct SkipPair {",
        "    pub block: u16,",
        "    pub neighbour: u16,",
        "    /// Whether every state pair hides it in every listed direction.",
        "    pub always: bool,",
        "    /// Bit `d` for each direction, in the tuple order, it was ever seen in.",
        "    pub directions: u8,",
        "}",
        "",
        f"pub const SHAPE_COUNT: usize = {data['shape_count']};",
        "",
        "#[rustfmt::skip]",
        f"pub static TUPLES: [[u8; 6]; {len(data['tuples'])}] = [",
    ]
    for kinds in data["tuples"]:
        out.append("    [" + ", ".join(str(kind) for kind in kinds) + "],")
    out += ["];", "", "#[rustfmt::skip]", f"pub static BLOCK_TUPLES: [&[u16]; {len(data['blocks'])}] = ["]
    for block in data["blocks"]:
        out.append("    &[" + ", ".join(str(t) for t in block["tuples"]) + "],")
    out += ["];", "", "#[rustfmt::skip]", f"pub static JOINS: [&str; {len(data['joins'])}] = ["]
    for line in data["joins"]:
        out.append(f'    "{line}",')
    out += ["];", "", "/// Row `a` column `b`: whether the two faces together cover the whole face.",
            "#[rustfmt::skip]", f"pub static COVERS: [&str; {len(data['covers'])}] = ["]
    for line in data["covers"]:
        out.append(f'    "{line}",')
    out += ["];", "", "#[rustfmt::skip]", f"pub static SKIPS: [SkipPair; {len(data['skip_pairs'])}] = ["]
    for pair in data["skip_pairs"]:
        mask = sum(1 << DIRECTIONS.index(d) for d in pair["directions"])
        out.append(
            f"    SkipPair {{ block: {index[pair['block']]}, neighbour: {index[pair['neighbour']]}, "
            f"always: {str(pair['always']).lower()}, directions: {mask} }},"
        )
    out += ["];", ""]
    with open("crates/voxel-data/src/block/face_occlusion.rs", "w", encoding="utf-8") as handle:
        handle.write("\n".join(out))
    print(f"tuples={len(data['tuples'])} shapes={data['shape_count']} skips={len(data['skip_pairs'])}")


if __name__ == "__main__":
    main(sys.argv[1])
