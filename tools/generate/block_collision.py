"""Generate src/world/block_collision_table.rs from a block-family capture.

    python3 tools/generate/block_collision.py .data/captures/behavior/<id>/outputs.jsonl

The capture is local; the generated table is committed, and the parity run
compares it with the reference on every pass.
"""
import json
import sys


def main(path):
    data = None
    for line in open(path, encoding="utf-8"):
        record = json.loads(line)
        if record["case_id"] == "block/collision-shapes":
            data = record["result"]["rows"][0]
    if data is None:
        raise SystemExit("no block/collision-shapes record in that capture")

    shapes, blocks = data["shapes"], data["blocks"]
    lines = [
        "//! Every block state's collision shape, taken from the reference.",
        "//!",
        "//! The shape a state blocks movement with is a table the reference builds in",
        "//! code. It is taken here as data, shapes are deduplicated by their boxes, and",
        "//! a block whose states all share one shape carries a single entry.",
        "//!",
        "//! The shapes are the ones the world's collision walk sees with no entity in",
        "//! the question. For a few blocks that is only the starting point: a random",
        "//! offset moves some with their position, and a handful are dynamic and read",
        "//! the entity or the block entity. Those blocks are flagged.",
        "//!",
        "//! This file is generated by `tools/generate/block_collision.py`.",
        "",
        "/// One box of a shape, as raw `f64` bits: min x, y, z then max x, y, z.",
        "pub type ShapeBox = [u64; 6];",
        "",
        "/// What one block's shapes are and how far to trust them.",
        "pub struct BlockCollision {",
        "    /// Indices into [`SHAPES`]: one for every state, or one per state.",
        "    pub shapes: &'static [u16],",
        "    /// The shape moves with the block's position by a random offset.",
        "    pub position_dependent: bool,",
        "    /// The reference recomputes the shape from context rather than caching it.",
        "    pub dynamic: bool,",
        "}",
        "",
        f"/// Every distinct shape, as its boxes.\npub static SHAPES: [&[ShapeBox]; {len(shapes)}] = [",
    ]
    for shape in shapes:
        boxes = ", ".join(
            "[" + ", ".join(f"0x{bits}" for bits in box) + "]" for box in shape
        )
        lines.append(f"    &[{boxes}],")
    lines.append("];")
    lines.append("")
    lines.append(
        f"/// Every block's collision, in registry order.\n"
        f"pub static BLOCKS: [BlockCollision; {len(blocks)}] = ["
    )
    for block in blocks:
        indices = ", ".join(str(index) for index in block["shapes"])
        lines.append(
            f"    BlockCollision {{ shapes: &[{indices}], "
            f"position_dependent: {str(block['position_dependent']).lower()}, "
            f"dynamic: {str(block['dynamic']).lower()} }},"
        )
    lines.append("];")
    with open("src/world/block_collision_table.rs", "w", encoding="utf-8") as out:
        out.write("\n".join(lines) + "\n")
    print(f"shapes={len(shapes)} blocks={len(blocks)}")


if __name__ == "__main__":
    main(sys.argv[1])
