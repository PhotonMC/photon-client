"""Generate src/potion_table.rs from a block-family capture.

    python3 tools/generate/potions.py .data/captures/behavior/<id>/outputs.jsonl

The mob effects (colour, description) and the potions (name, effects) by
registry id, from the reference. A potion's colour and name are read from
them. The capture is local; the generated table is committed, and the parity
run compares it with the reference on every pass.
"""
import json
import sys


def main(path):
    data = None
    for line in open(path, encoding="utf-8"):
        case = json.loads(line)
        if case["case_id"] == "block/potions":
            data = case["result"]["rows"][0]
    if data is None:
        raise SystemExit("no block/potions case in the capture")
    out = [
        "//! The mob effects and the potions by registry id, from the reference.",
        "//!",
        "//! This file is generated by `tools/generate/potions.py`.",
        "",
        "pub struct MobEffect {",
        "    pub name: &'static str,",
        "    /// `MobEffect.getColor`, `0xRRGGBB`.",
        "    pub color: i32,",
        "    pub description_id: &'static str,",
        "}",
        "",
        "/// One effect a potion gives.",
        "pub struct PotionEffect {",
        "    pub effect: i32,",
        "    pub amplifier: i32,",
        "    pub duration: i32,",
        "    pub visible: bool,",
        "}",
        "",
        "pub struct Potion {",
        "    pub name: &'static str,",
        "    /// `Potion.name`, which names the potion's item translation.",
        "    pub potion_name: &'static str,",
        "    pub effects: &'static [PotionEffect],",
        "}",
        "",
        "#[rustfmt::skip]",
        f"pub static MOB_EFFECTS: [MobEffect; {len(data['effects'])}] = [",
    ]
    for effect in data["effects"]:
        out.append(
            f'    MobEffect {{ name: "{effect["name"]}", color: {effect["color"]}, '
            f'description_id: "{effect["description_id"]}" }},'
        )
    out.append("];")
    out.append("")
    out.append("#[rustfmt::skip]")
    out.append(f"pub static POTIONS: [Potion; {len(data['potions'])}] = [")
    for potion in data["potions"]:
        effects = ", ".join(
            f'PotionEffect {{ effect: {e["effect"]}, amplifier: {e["amplifier"]}, '
            f'duration: {e["duration"]}, visible: {str(e["visible"]).lower()} }}'
            for e in potion["effects"]
        )
        out.append(
            f'    Potion {{ name: "{potion["name"]}", potion_name: "{potion["potion_name"]}", '
            f"effects: &[{effects}] }},"
        )
    out.append("];")
    out.append("")
    open("src/potion_table.rs", "w", encoding="utf-8").write("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
