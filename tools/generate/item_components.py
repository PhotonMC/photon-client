"""Generate crates/voxel-data/src/item/components.rs from a block-family capture.

    python3 tools/generate/item_components.py .data/captures/behavior/<id>/outputs.jsonl

Every item's default components as a component patch, as a server sends it,
in registry order, from the reference. The port that reads patches is run
over each one on every parity pass, and its writing of the delimited form
is compared with the reference's. The capture is local; the generated table
is committed.
"""
import json
import sys


def main(path):
    data = None
    for line in open(path, encoding="utf-8"):
        case = json.loads(line)
        if case["case_id"] == "block/item-components":
            data = case["result"]["rows"][0]
    if data is None:
        raise SystemExit("no block/item-components case in the capture")
    out = [
        "//! Every item's default components as a component patch, as a server",
        "//! sends it, in registry order, from the reference (hexadecimal).",
        "//!",
        "//! This file is generated by `tools/generate/item_components.py`.",
        "",
        "#[rustfmt::skip]",
        f"pub static ITEM_COMPONENT_WIRES: [&str; {len(data['items'])}] = [",
    ]
    for item in data["items"]:
        out.append(f'    "{item["wire"]}", // {item["name"]}')
    out.append("];")
    out.append("")
    open("crates/voxel-data/src/item/components.rs", "w", encoding="utf-8").write("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
