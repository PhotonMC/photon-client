#!/usr/bin/env python3
"""Generate the repository's document index from docs/ and docs/records/."""

from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"
RECORDS = DOCS / "records"
INDEX = DOCS / "index.md"

CORE_NAMES = {
    "behavior-runner.md",
    "behavior-testing.md",
    "coding-standards.md",
    "course-correction-2026-09-12.md",
    "first-behavior-tests.md",
    "reference-baseline.md",
    "reference-data.md",
    "remaining-test-plan.md",
    "roadmap.md",
    "source-review.md",
}


def title(path: Path) -> str:
    for line in path.read_text().splitlines():
        if line.startswith("# "):
            return (
                line[2:]
                .strip()
                .replace("[client-parity]", "client-parity")
                .replace("[server-conformance]", "server-conformance")
            )
    return path.stem.replace("-", " ")


def grouped_documents() -> list[tuple[str, list[Path]]]:
    documents = sorted(
        (path for path in [*DOCS.glob("*.md"), *RECORDS.glob("*.md")] if path.name != INDEX.name),
        key=lambda path: path.name,
    )
    core = [path for path in documents if path.name in CORE_NAMES]
    conformance = [
        path
        for path in documents
        if path.name.endswith("-conformance.md") and path not in core
    ]
    remaining = [path for path in documents if path not in core and path not in conformance]
    groups = [
        ("Proje ve test yönlendirmeleri", core),
        ("Birleşik davranış sözleşmeleri ve kanıtları", conformance),
        ("Diğer referans kayıtları", remaining),
    ]
    return [(heading, paths) for heading, paths in groups if paths]


def main() -> None:
    lines = [
        "<!-- This file is generated by tools/generate-doc-index.py. -->",
        "# Belge dizini",
        "",
        "Davranış kayıtları tek dosyada sözleşme ve kanıt bölümleriyle tutulur.",
        "Bu dizin `tools/generate-doc-index.py` ile `docs/` ve `docs/records/` içeriğinden üretilir.",
    ]
    for heading, documents in grouped_documents():
        lines.extend(["", f"## {heading}", ""])
        lines.extend(f"- [{title(path)}]({path.relative_to(DOCS).as_posix()})" for path in documents)
    INDEX.write_text("\n".join(lines).rstrip() + "\n")


if __name__ == "__main__":
    main()
