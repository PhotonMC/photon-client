pub fn data_ids() -> Vec<Value> {
    let rows = ACCESSORS
        .iter()
        .map(|(class, field)| {
            let name = class.rsplit('.').next().unwrap_or(class);
            json!({"label": format!("{name}.{field}"), "class": class, "field": field})
        })
        .collect();
    vec![entity("data-ids", "entity_data_ids", rows)]
}
