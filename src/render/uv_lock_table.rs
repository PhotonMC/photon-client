//! The UV lock tables, read from the reference.
//!
//! With UV lock on, a face's texture keeps its world orientation while the
//! model turns. The reference works this out once at startup by composing
//! quaternions and inverting the result, and caches one table per element of
//! the cube symmetry group.
//!
//! Those tables are **not exact**. Probing them shows entries like
//! `0.99999994` and `-1.0000001`, float error left over from the quaternion
//! path. Recomputing them would mean reproducing the matrix library's
//! `rotate`, `mul` and `invertAffine` to the letter, and those formulas are
//! not in the reference source we have. So the tables are taken from the
//! reference as data rather than guessed at, and the parity run compares
//! every entry on every pass.
//!
//! This file is generated; the slice record says from what.

