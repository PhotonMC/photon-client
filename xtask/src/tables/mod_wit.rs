//! The WIT of the mod API, written from the tables of `photon-api`.

use photon_api::{CAPABILITIES, EXPORTS, IMPORTS, Import};

use super::Versions;

/// The package a guest's WIT depends on.
const PACKAGE: &str = "photon:mod@0.1.0";

/// The world of one capability: `hud.text` is `cap-hud-text`.
fn world_name(capability: &str) -> String {
    format!("cap-{}", capability.replace(['.', '_'], "-"))
}

fn signature(import: &Import) -> String {
    let params: Vec<String> = import
        .params
        .iter()
        .map(|(name, ty)| format!("{name}: {}", ty.wit()))
        .collect();
    let result = import
        .result
        .map_or(String::new(), |ty| format!(" -> {}", ty.wit()));
    format!("func({}){result}", params.join(", "))
}

pub fn render(_: &Versions) -> Result<String, String> {
    let mut out = String::from(
        "// @generated by `cargo xtask gen` (mod-wit); do not edit by hand.\n\
         //\n\
         // The functions a Photon client's mod host links, from `photon-api`. They are root-level\n\
         // functions of the component, as the first mods were built. A manifest asks for\n\
         // capabilities by name; the host refuses a component that imports a function whose\n\
         // capability it did not ask for, and no `wasi:*` import is linked. Each capability has a\n\
         // world, `cap-<name with dashes>`; a guest includes the worlds of the capabilities it asks\n\
         // for, and `photon-mod` is all of them. The export `tick` is required exactly when the mod asks\n\
         // for `events.tick` (world `cap-events-tick`); a mod without that capability needs no\n\
         // `tick` and is never called.\n",
    );
    out.push_str(&format!("package {PACKAGE};\n"));
    for cap in CAPABILITIES {
        out.push_str(&format!(
            "\n/// `{}`: {}\nworld {} {{\n",
            cap.name,
            cap.doc,
            world_name(cap.name)
        ));
        for export in EXPORTS.iter().filter(|e| e.capability == cap.name) {
            out.push_str(&format!(
                "    /// {}\n    export {}: func();\n",
                export.doc, export.name
            ));
        }
        for import in IMPORTS.iter().filter(|i| i.capability == cap.name) {
            out.push_str(&format!(
                "    /// {}\n    import {}: {};\n",
                import.doc,
                import.name,
                signature(import)
            ));
        }
        out.push_str("}\n");
    }
    out.push_str("\n/// Every capability.\nworld photon-mod {\n");
    for cap in CAPABILITIES {
        out.push_str(&format!("    include {};\n", world_name(cap.name)));
    }
    out.push_str("}\n");
    Ok(out)
}
